<!-- JavaScript for Why Choose Section Animation -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const advantageElements = document.querySelectorAll('.advantage-anim');
        
        const advantageObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.remove('opacity-0', 'translate-y-8', 'translate-y-10');
                    entry.target.classList.add('opacity-100', 'translate-y-0');
                    observer.unobserve(entry.target);
                }
            });
        }, { threshold: 0.1 });

        advantageElements.forEach(el => {
            advantageObserver.observe(el);
        });
    });
</script>